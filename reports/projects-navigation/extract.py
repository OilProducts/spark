"""Derive navigation-mockup data from the real Spark home. Writes data.js next to this file."""
import json, os, re, tomllib

HOME = os.path.expanduser('~/Library/Application Support/dev.spark.desktop/spark')
WS = os.path.join(HOME, 'workspace/projects')
RUNS = os.path.join(HOME, 'attractor/runs')

def mission_ts(v):
    m = re.match(r'(\d{4}-\d{2}-\d{2})[ T](\d{1,2}):(\d{2}):(\d{2})', v or '')
    return f'{m.group(1)}T{int(m.group(2)):02d}:{m.group(3)}:{m.group(4)}Z' if m else None

projects = []
for pid in sorted(os.listdir(WS)):
    meta = tomllib.load(open(os.path.join(WS, pid, 'project.toml'), 'rb'))
    chats = []
    cdir = os.path.join(WS, pid, 'conversations')
    for cid in os.listdir(cdir) if os.path.isdir(cdir) else []:
        path = os.path.join(cdir, cid, 'conversation.json')
        if not os.path.exists(path) or cid.startswith(('mission-', 'task-')):
            continue
        c = json.load(open(path))
        launches = []
        lp = os.path.join(cdir, cid, 'artifacts', 'flow-launches.json')
        if os.path.exists(lp):
            data = json.load(open(lp))
            for a in data if isinstance(data, list) else data.get('flow_launches', []):
                if a.get('run_id'):
                    launches.append({'run': a['run_id'], 'at': a.get('created_at'), 'flow': a.get('flow_name')})
        chats.append({'id': cid, 'title': (c.get('title') or '').strip() or 'New thread', 'handle': c.get('conversation_handle'),
                      'updated': c.get('updated_at'), 'created': c.get('created_at'), 'provider': c.get('provider'), 'model': c.get('model'),
                      'launches': launches})
    chats.sort(key=lambda c: c['updated'] or '', reverse=True)
    missions = []
    mdir = os.path.join(WS, pid, 'missions')
    for f in os.listdir(mdir) if os.path.isdir(mdir) else []:
        if not f.endswith('.json'):
            continue
        m = json.load(open(os.path.join(mdir, f)))
        status = 'closed' if m.get('closed') else 'draft' if not m.get('started_at') else 'running'
        missions.append({'id': m['id'], 'title': m['fields']['title'], 'status': status, 'archived': m['fields'].get('archived'),
                         'runs': [r['run_id'] for r in m.get('runs') or []], 'created': mission_ts(m.get('created_at')),
                         'closed': (m.get('closed') or {}).get('status'), 'updated': mission_ts(m.get('updated_at'))})
    runs = []
    rdir = os.path.join(RUNS, pid)
    for rid in os.listdir(rdir) if os.path.isdir(rdir) else []:
        p = os.path.join(rdir, rid, 'run.json')
        if not os.path.exists(p):
            continue
        r = json.load(open(p))
        if r.get('parent_run_id'):
            continue
        runs.append({'id': rid, 'title': r.get('title'), 'flow': r.get('flow_name'), 'status': r.get('status'), 'trigger': bool(r.get('trigger_id') or (r.get('launch_origin') or {}).get('trigger_id')),
                     'started': r.get('started_at'), 'ended': r.get('ended_at'),
                     'input': next((v.split('\n')[0][:120] for v in (r.get('launch_context') or {}).values() if isinstance(v, str) and v.strip()), None)})
    runs.sort(key=lambda r: r['started'] or '', reverse=True)
    projects.append({'id': pid, 'name': meta.get('display_name') or os.path.basename(meta['project_path']), 'path': meta['project_path'],
                     'exists': os.path.isdir(meta['project_path']), 'lastOpened': meta.get('last_accessed_at') or meta.get('last_opened_at'),
                     'favorite': meta.get('is_favorite', False), 'chats': chats, 'missions': missions, 'runs': runs, 'runCount': len(runs)})

triggers = []
tdir = os.path.join(HOME, 'config/triggers')
for f in sorted(os.listdir(tdir)):
    if f.endswith('.toml'):
        t = tomllib.load(open(os.path.join(tdir, f), 'rb'))
        action = t.get('action') or {}
        triggers.append({'id': t.get('id'), 'name': t.get('name'), 'source': t.get('source_type') or (t.get('source') or {}).get('type'),
                         'enabled': t.get('enabled'), 'project': action.get('project_path'), 'mode': action.get('mode'), 'flow': action.get('flow_name')})

flows = []
fdir = os.path.join(HOME, 'flows')
for root, _, files in os.walk(fdir):
    for f in files:
        if f.endswith(('.yaml', '.yml')):
            flows.append(os.path.relpath(os.path.join(root, f), fdir))
flows.sort()

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, 'data.js'), 'w') as f:
    f.write('// Generated by extract.py from the real Spark home. Do not edit by hand.\nconst DATA = ')
    json.dump({'projects': projects, 'triggers': triggers, 'flows': flows}, f, indent=1, ensure_ascii=False)
    f.write(';\n')
for p in projects:
    print(p['name'], p['exists'], len(p['chats']), len(p['missions']), p['runCount'])
print(triggers)
